// Rebuilds skills/chat-to-article/SKILL.zip for uploading to claude.ai.
// Runs after every commit via .githooks/post-commit; also `npm run zip`.
// The zip holds a chat-to-article/ folder with every file in the skill folder except the zip itself.
// Written without dependencies: a minimal zip writer using node:zlib.

import { deflateRawSync, crc32 } from "node:zlib";
import { readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillDir = join(root, "skills/chat-to-article");
const zipPath = join(skillDir, "SKILL.zip");
const folder = "chat-to-article";

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return listFiles(p);
    return p === zipPath || name === ".DS_Store" ? [] : [p];
  });
}

// DOS date/time for the zip headers.
const now = new Date();
const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1);
const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();

const locals: Buffer[] = [];
const centrals: Buffer[] = [];
let offset = 0;

const files = listFiles(skillDir).sort();
for (const file of files) {
  const name = Buffer.from(`${folder}/${relative(skillDir, file).split("\\").join("/")}`, "utf8");
  const data = readFileSync(file);
  const packed = deflateRawSync(data);
  const crc = crc32(data);

  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0);
  local.writeUInt16LE(20, 4); // version needed
  local.writeUInt16LE(0x0800, 6); // UTF-8 names
  local.writeUInt16LE(8, 8); // deflate
  local.writeUInt16LE(dosTime, 10);
  local.writeUInt16LE(dosDate, 12);
  local.writeUInt32LE(crc, 14);
  local.writeUInt32LE(packed.length, 18);
  local.writeUInt32LE(data.length, 22);
  local.writeUInt16LE(name.length, 26);
  local.writeUInt16LE(0, 28);
  locals.push(local, name, packed);

  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0);
  central.writeUInt16LE(20, 4); // version made by
  central.writeUInt16LE(20, 6);
  central.writeUInt16LE(0x0800, 8);
  central.writeUInt16LE(8, 10);
  central.writeUInt16LE(dosTime, 12);
  central.writeUInt16LE(dosDate, 14);
  central.writeUInt32LE(crc, 16);
  central.writeUInt32LE(packed.length, 20);
  central.writeUInt32LE(data.length, 24);
  central.writeUInt16LE(name.length, 28);
  central.writeUInt32LE(offset, 42);
  centrals.push(central, name);

  offset += local.length + name.length + packed.length;
}

const centralSize = centrals.reduce((n, b) => n + b.length, 0);
const end = Buffer.alloc(22);
end.writeUInt32LE(0x06054b50, 0);
end.writeUInt16LE(files.length, 8);
end.writeUInt16LE(files.length, 10);
end.writeUInt32LE(centralSize, 12);
end.writeUInt32LE(offset, 16);

rmSync(zipPath, { force: true });
writeFileSync(zipPath, Buffer.concat([...locals, ...centrals, end]));
console.log(`zip-skill: wrote ${relative(root, zipPath)} (${files.map((f) => relative(skillDir, f)).join(", ")})`);
